import { useCallback, useEffect, useMemo, useRef, useState } from "react";
import { renderDiagram, type Diagram } from "./diagram";
import { useTerminalRun } from "./terminalRun";

// Icons for the command-chip affordances. Inline SVG (not lucide) because these
// hang off server-rendered prose we enhance in the DOM, not off JSX. They use
// currentColor so .cmd-btn's text colour drives them.
const COPY_SVG =
  '<svg width="13" height="13" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><rect x="9" y="9" width="13" height="13" rx="2"/><path d="M5 15H4a2 2 0 0 1-2-2V4a2 2 0 0 1 2-2h9a2 2 0 0 1 2 2v1"/></svg>';
const CHECK_SVG =
  '<svg width="13" height="13" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5" stroke-linecap="round" stroke-linejoin="round"><path d="M20 6 9 17l-5-5"/></svg>';
const PLAY_SVG =
  '<svg width="13" height="13" viewBox="0 0 24 24" fill="currentColor" stroke="none"><path d="M8 5v14l11-7z"/></svg>';
// Shown on the run button from click until the command is actually written to
// the shell - which is a real wait while a nested lab provisions. The arc spins
// via .cd-spin (see index.css).
const SPINNER_SVG =
  '<svg class="cd-spin" width="13" height="13" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5" stroke-linecap="round"><path d="M21 12a9 9 0 1 1-6.219-8.56"/></svg>';

// The course player: a port of the training-guide template's engine (stepper,
// dots, `aha` reveal, quiz flagging, keyboard nav), reskinned onto the app's
// slate/blue tokens and laid out for a side pane rather than a full page.
//
// The template's two-column card stacks below 900px - diagram on top, prose
// below - and that stacked form IS the side-pane layout, so nothing had to be
// invented here beyond the vertical flow.
//
// Two deliberate departures from the template:
//
//   - Progress is not localStorage. The template persists the current step in
//     the browser; ours reports answers upward so the server owns them, because
//     completion is a real claim about a student and must survive a device
//     change.
//   - You can always advance past an unanswered quiz. Unanswered questions are
//     collected at the end instead of blocking the lesson, so nobody is stuck
//     on question 3 unable to read the screen that explains it.

export type QuizOption = { t: string; correct?: boolean };

export type Step = {
  slug: string;
  index: number;
  kind: "concept" | "quiz" | "flag";
  ey: string;
  eyt: string;
  tag?: string;
  chip?: { label: string; tone: "accent" | "warn" | "danger" };
  diagram?: Diagram;
  // concept
  title?: string;
  body?: string; // pre-rendered, restricted HTML from internal/course/prose.go
  aha?: string;
  revealLabel?: string;
  // quiz - q and each option's `t` arrive as inline HTML from the same
  // restricted renderer as body/aha, so a term named in a question shows the
  // same chip the concept screens used instead of literal backticks.
  q?: string;
  opts?: QuizOption[];
  explain?: string;
};

export type Answers = Record<string, number>; // step slug -> chosen option index

const chipTone: Record<string, string> = {
  accent: "bg-blue-500/10 text-blue-300 ring-blue-500/30",
  warn: "bg-amber-500/10 text-amber-300 ring-amber-500/30",
  danger: "bg-red-500/10 text-red-300 ring-red-500/30",
};

function DiagramStage({ diagram }: { diagram?: Diagram }) {
  const html = useMemo(() => (diagram ? renderDiagram(diagram) : ""), [diagram]);
  if (!diagram) return null;
  return (
    <div className="relative mb-4 rounded-lg border border-slate-800 bg-slate-900/60 p-2">
      {/* The SVG is generated by our own renderer from schema-validated data -
          never from author markup - see diagram.ts. */}
      <div className="cd-stage" dangerouslySetInnerHTML={{ __html: html }} />
    </div>
  );
}

export default function CoursePlayer({
  steps,
  answers,
  onAnswer,
  moduleName,
  onStart,
  courseKey,
  complete = false,
  progressReady = false,
  onSubmitFlag,
  onReset,
  onStepChange,
}: {
  steps: Step[];
  answers: Answers;
  onAnswer: (stepSlug: string, optionIndex: number) => void;
  moduleName: string;
  // Fires when the student leaves the opening screen (the "Start →" button), so
  // beginning the course also boots the lab. No-op / idempotent on the caller's
  // side once a session exists.
  onStart?: () => void;
  // Whether the lab is solved (the captured flag was accepted). Server-owned,
  // passed down so the flag capstone can show its solved state.
  complete?: boolean;
  // Whether `complete` reflects a loaded progress fetch rather than the default.
  // The opening-placement effect waits on this so a slow progress load can't
  // first strand a solved reader on page 0 before `complete` flips true.
  progressReady?: boolean;
  // Submits the flag the student captured; resolves to whether it was correct.
  // The caller owns persisting completion (and refetching progress), so this
  // component just drives the form state from the result.
  onSubmitFlag?: (flag: string) => Promise<{ correct: boolean; complete: boolean }>;
  // Clears this lab's progress (answers + completion) so the student can retake
  // it. The caller refetches progress, which flows back as empty answers and
  // complete=false.
  onReset?: () => void;
  // Per-lab identity (the module slug). Used only to remember which screen the
  // student was last on, per lab, in localStorage. NOTE: this is view position,
  // not progress - answers/completion stay server-owned (see the header note).
  // The caller keys this component on the same value, so switching labs remounts
  // it and re-reads THIS lab's saved page rather than leaking the previous one's.
  courseKey?: string;
  // Fires whenever the visible step changes (and on mount), with the current
  // 0-based index and the step count. The caller reports it to the backend so
  // the AI tutor knows where the student is in the guided course. Read through a
  // ref below so an inline callback can't retrigger the effect every render.
  onStepChange?: (index: number, total: number) => void;
}) {
  const pageKey = courseKey ? `k8labs:course-page:${courseKey}` : null;
  const [idx, setIdx] = useState(() => {
    if (!pageKey) return 0;
    const raw = localStorage.getItem(pageKey);
    const n = raw ? parseInt(raw, 10) : 0;
    if (!Number.isFinite(n) || n < 0) return 0;
    // Clamp: the course may have gained or lost screens since we saved.
    return Math.min(n, Math.max(0, steps.length - 1));
  });
  const [revealed, setRevealed] = useState(false);
  // Flag capstone form. `wrong` shows the "not quite" hint after a rejected
  // submit; it clears as soon as the student edits the field again.
  const [flagInput, setFlagInput] = useState("");
  const [flagStatus, setFlagStatus] = useState<"idle" | "submitting" | "wrong">("idle");
  // Two-click confirm for the destructive restart, so a stray click can't wipe
  // a student's progress. Resets whenever they navigate away from the capstone.
  const [confirmReset, setConfirmReset] = useState(false);

  // Remember the current screen per lab, so leaving and returning (or a reload)
  // lands back where the student was rather than at the start.
  useEffect(() => {
    if (!pageKey) return;
    try {
      localStorage.setItem(pageKey, String(idx));
    } catch {
      // Private mode / quota - remembering the page is a nicety, not worth throwing.
    }
  }, [pageKey, idx]);

  // Report the current step to the caller (which relays it to the AI tutor)
  // whenever it changes, and once on mount. Held in a ref so passing an inline
  // onStepChange doesn't make this effect re-run on every render - it fires only
  // when idx or the step count actually change.
  const onStepChangeRef = useRef(onStepChange);
  onStepChangeRef.current = onStepChange;
  useEffect(() => {
    onStepChangeRef.current?.(idx, steps.length);
  }, [idx, steps.length]);

  // Opening a solved lab lands on the final "Solved / what this proves" screen
  // rather than the reader's saved page: once the flag is captured, the takeaway
  // is the natural place to return to. Done once per mount (a real reopen
  // remounts, keyed on the lab, and re-places) so a solved reader who pages back
  // to review isn't yanked forward again. Gated on progressReady so we act only
  // when `complete` is the loaded truth, not its pre-fetch default.
  const placedRef = useRef(false);
  useEffect(() => {
    if (placedRef.current || !progressReady) return;
    placedRef.current = true;
    if (complete) setIdx(Math.max(0, steps.length - 1));
  }, [progressReady, complete, steps.length]);

  const paneRef = useRef<HTMLDivElement>(null);
  // Latest terminal bridge in a ref, so the DOM-enhancement effect below can
  // stay keyed on the content (not on `run`) yet always call the current one.
  const run = useTerminalRun();
  const runRef = useRef(run);
  runRef.current = run;

  const total = steps.length;
  const step = steps[idx];

  const atEnd = idx === total - 1;

  const go = useCallback(
    (next: number) => {
      if (next < 0 || next > total - 1) return;
      // Leaving the opening screen for the first time boots the lab, so the
      // course and the session start together. Guarded to idx 0 -> forward so
      // paging back and forth doesn't re-fire it.
      if (idx === 0 && next > 0) onStart?.();
      setIdx(next);
      setRevealed(false);
      setConfirmReset(false);
      paneRef.current?.scrollTo({ top: 0 });
    },
    [total, idx, onStart],
  );

  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      // Don't hijack arrows while someone is typing in the terminal or a field.
      const el = document.activeElement;
      if (el && (el.tagName === "INPUT" || el.tagName === "TEXTAREA" || (el as HTMLElement).isContentEditable)) return;
      if (e.key === "ArrowRight") go(idx + 1);
      else if (e.key === "ArrowLeft") go(idx - 1);
    };
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [idx, go]);

  // Editor-style spec blocks (course/prose.go's renderSpecGroup) are server-
  // rendered with their tabs and panes; clicking a tab is the only interaction,
  // wired here by delegation so it survives the dangerouslySetInnerHTML content.
  // Keyed on the visible content so a new step's groups get the handler too.
  useEffect(() => {
    const root = paneRef.current;
    if (!root) return;
    const onClick = (e: MouseEvent) => {
      const tab = (e.target as HTMLElement).closest<HTMLElement>(".spec-tab");
      if (!tab) return;
      const group = tab.closest(".spec-group");
      if (!group) return;
      const i = tab.dataset.specI;
      group.querySelectorAll<HTMLElement>(".spec-tab").forEach((t) => {
        t.classList.toggle("is-active", t.dataset.specI === i);
      });
      group.querySelectorAll<HTMLElement>(".spec-pane").forEach((p) => {
        p.classList.toggle("is-active", p.dataset.specI === i);
      });
    };
    root.addEventListener("click", onClick);
    return () => root.removeEventListener("click", onClick);
  }, [step, revealed]);

  // Hang copy + run affordances off each runnable-command chip (`$ cmd` in the
  // source -> <span class="k cmd" data-cmd>). The prose is server-rendered HTML
  // injected via dangerouslySetInnerHTML, so we enhance it in the DOM after each
  // paint. Re-runs when the visible content changes - the step, or the aha
  // reveal - and the guard keeps a re-run from double-decorating a chip.
  useEffect(() => {
    const root = paneRef.current;
    if (!root) return;
    const cleanups: Array<() => void> = [];
    root.querySelectorAll<HTMLElement>("span.cmd[data-cmd]").forEach((chip) => {
      if (chip.dataset.enhanced === "1") return;
      chip.dataset.enhanced = "1";
      const cmd = chip.getAttribute("data-cmd") || chip.textContent || "";

      const mkBtn = (svg: string, label: string) => {
        const b = document.createElement("button");
        b.type = "button";
        b.className = "cmd-btn";
        b.title = label;
        b.setAttribute("aria-label", label);
        b.innerHTML = svg;
        return b;
      };
      const copyBtn = mkBtn(COPY_SVG, "Copy command");
      const runBtn = mkBtn(PLAY_SVG, "Run in the lab terminal");

      let copyTimer = 0;
      let runTimer = 0;
      let runBusy = false;
      const onCopy = () => {
        navigator.clipboard
          ?.writeText(cmd)
          .then(() => {
            copyBtn.innerHTML = CHECK_SVG;
            copyBtn.classList.add("done");
            window.clearTimeout(copyTimer);
            copyTimer = window.setTimeout(() => {
              copyBtn.innerHTML = COPY_SVG;
              copyBtn.classList.remove("done");
            }, 1100);
          })
          .catch(() => {});
      };
      // Spinner from click until the command is actually written to the shell.
      // While the lab is still provisioning that write is queued, so this is the
      // only signal the click landed - without it the play icon sits there inert
      // until the command silently appears. A floor keeps the spinner visible
      // even when the shell is already connected and the send is instant.
      const onRun = () => {
        if (runBusy) return;
        runBusy = true;
        runBtn.disabled = true;
        runBtn.classList.add("busy");
        runBtn.innerHTML = SPINNER_SVG;
        const started = Date.now();
        const settle = () => {
          const restore = () => {
            runBtn.innerHTML = PLAY_SVG;
            runBtn.classList.remove("busy");
            runBtn.disabled = false;
            runBusy = false;
          };
          window.clearTimeout(runTimer);
          runTimer = window.setTimeout(restore, Math.max(0, 450 - (Date.now() - started)));
        };
        const p = runRef.current?.runCommand(cmd);
        if (p && typeof p.then === "function") p.then(settle, settle);
        else settle();
      };
      copyBtn.addEventListener("click", onCopy);
      runBtn.addEventListener("click", onRun);

      const actions = document.createElement("span");
      actions.className = "cmd-actions";
      actions.append(copyBtn, runBtn);
      chip.after(actions);

      cleanups.push(() => {
        window.clearTimeout(copyTimer);
        window.clearTimeout(runTimer);
        copyBtn.removeEventListener("click", onCopy);
        runBtn.removeEventListener("click", onRun);
        actions.remove();
        delete chip.dataset.enhanced;
      });
    });
    return () => cleanups.forEach((fn) => fn());
  }, [step, revealed]);

  if (!step) {
    return (
      <div className="flex h-full items-center justify-center px-6 text-center text-sm text-slate-600">
        This lab doesn't have a guided course yet. The terminal on the right still works.
      </div>
    );
  }

  const answered = answers[step.slug];
  const correctIdx = step.opts?.findIndex((o) => o.correct) ?? -1;

  // Submit the captured flag. A wrong flag is a normal result (correct=false),
  // shown as the "not quite" hint; only a transport/auth failure is an error.
  // On success the parent flips `complete`, which drives the solved state.
  const submitFlagForm = async () => {
    const value = flagInput.trim();
    if (!value || !onSubmitFlag || flagStatus === "submitting") return;
    setFlagStatus("submitting");
    try {
      const res = await onSubmitFlag(value);
      setFlagStatus(res.correct ? "idle" : "wrong");
    } catch {
      setFlagStatus("wrong");
    }
  };

  // Destructive: first click arms, second click clears. onReset wipes answers +
  // completion server-side; the parent refetches, which re-enables the quizzes.
  const doReset = () => {
    if (!onReset) return;
    if (!confirmReset) {
      setConfirmReset(true);
      return;
    }
    setConfirmReset(false);
    setFlagInput("");
    setFlagStatus("idle");
    // A restart is a fresh start: drop back to the first screen and forget the
    // saved page, so this reset - and any later reopen - begins at the intro
    // rather than the capstone we just cleared. (Same mount, so the opening
    // placement effect above won't re-fire; this is what resets the view.)
    setIdx(0);
    if (pageKey) {
      try {
        localStorage.removeItem(pageKey);
      } catch {
        // Private mode / quota - clearing the saved page is best-effort.
      }
    }
    onReset();
  };

  return (
    <div className="flex h-full min-h-0 flex-col">
      {/* eyebrow */}
      <div className="flex shrink-0 items-center gap-2 px-5 pt-4 font-mono text-11 uppercase tracking-wider text-slate-500">
        <span className="text-blue-400">{step.ey}</span>
        <span>{step.eyt}</span>
        {step.chip ? (
          <span className={`ml-auto rounded-full px-2 py-0.5 text-10 ring-1 ring-inset ${chipTone[step.chip.tone]}`}>
            {step.chip.label}
          </span>
        ) : step.tag ? (
          <span className="ml-auto tracking-wide">{step.tag}</span>
        ) : null}
      </div>

      <div ref={paneRef} className="min-h-0 flex-1 overflow-y-auto px-5 pb-4 pt-3">
        <DiagramStage diagram={step.diagram} />

        {step.kind === "concept" ? (
          <>
            <h3 className="text-26 font-semibold leading-snug text-slate-100">{step.title}</h3>
            <div
              className="cd-prose mt-3 text-18 leading-relaxed text-slate-300"
              dangerouslySetInnerHTML={{ __html: step.body ?? "" }}
            />
            {step.aha && (
              <div className="mt-4">
                <button
                  onClick={() => setRevealed((r) => !r)}
                  className="rounded-lg border border-dashed border-blue-500/60 px-3 py-2 font-mono text-11 text-blue-300 transition-colors hover:bg-blue-500/10"
                >
                  {revealed ? "▴ hide" : `▾ ${step.revealLabel || "reveal the intuition"}`}
                </button>
                {revealed && (
                  <div
                    className="cd-prose mt-2.5 rounded-lg border border-blue-500/40 bg-blue-500/10 px-4 py-3 text-17 leading-relaxed text-slate-200"
                    dangerouslySetInnerHTML={{ __html: step.aha }}
                  />
                )}
              </div>
            )}
          </>
        ) : step.kind === "quiz" ? (
          <>
            <h3
              className="cd-prose text-22 font-semibold leading-snug text-slate-100"
              dangerouslySetInnerHTML={{ __html: step.q ?? "" }}
            />
            <div className="mt-4 flex flex-col gap-2">
              {step.opts?.map((o, i) => {
                const isAnswered = answered !== undefined;
                const isCorrect = i === correctIdx;
                const picked = answered === i;
                let cls = "border-slate-800 bg-slate-900 hover:border-slate-600";
                if (isAnswered && isCorrect) cls = "border-emerald-500 bg-emerald-500/10";
                else if (isAnswered && picked) cls = "border-red-500 bg-red-500/10";
                else if (isAnswered) cls = "border-slate-800 bg-slate-900 opacity-60";
                return (
                  <button
                    key={i}
                    disabled={isAnswered}
                    onClick={() => onAnswer(step.slug, i)}
                    className={`flex items-center gap-3 rounded-lg border px-3 py-2.5 text-left text-17 text-slate-200 transition-colors ${cls}`}
                  >
                    <span className="flex h-[22px] w-[22px] shrink-0 items-center justify-center rounded-md border border-slate-700 font-mono text-11 text-slate-400">
                      {String.fromCharCode(65 + i)}
                    </span>
                    <span dangerouslySetInnerHTML={{ __html: o.t }} />
                  </button>
                );
              })}
            </div>
            {answered !== undefined && (
              <div className="cd-prose mt-3 rounded-lg border border-blue-500/40 bg-blue-500/10 px-4 py-3 text-17 leading-relaxed text-slate-200">
                <b className={answered === correctIdx ? "text-emerald-400" : "text-amber-400"}>
                  {answered === correctIdx ? "Right. " : "Not quite. "}
                </b>
                <span dangerouslySetInnerHTML={{ __html: step.explain ?? "" }} />
              </div>
            )}
          </>
        ) : (
          // Flag capstone: the lab is solved by pasting the captured flag, not by
          // answering the quizzes. Renders like a concept (title/body/optional
          // reveal) plus the submission form and the restart control.
          <>
            <h3 className="text-26 font-semibold leading-snug text-slate-100">{step.title}</h3>
            <div
              className="cd-prose mt-3 text-18 leading-relaxed text-slate-300"
              dangerouslySetInnerHTML={{ __html: step.body ?? "" }}
            />
            {step.aha && (
              <div className="mt-4">
                <button
                  onClick={() => setRevealed((r) => !r)}
                  className="rounded-lg border border-dashed border-blue-500/60 px-3 py-2 font-mono text-11 text-blue-300 transition-colors hover:bg-blue-500/10"
                >
                  {revealed ? "▴ hide" : `▾ ${step.revealLabel || "reveal the intuition"}`}
                </button>
                {revealed && (
                  <div
                    className="cd-prose mt-2.5 rounded-lg border border-blue-500/40 bg-blue-500/10 px-4 py-3 text-17 leading-relaxed text-slate-200"
                    dangerouslySetInnerHTML={{ __html: step.aha }}
                  />
                )}
              </div>
            )}

            {complete ? (
              <div className="mt-5 rounded-lg border border-emerald-500/40 bg-emerald-500/10 p-4">
                <p className="text-15 font-semibold text-emerald-300">Solved - {moduleName} complete.</p>
                <p className="mt-1 text-13 text-slate-400">
                  Your flag was accepted. Restart the lab if you want to run it again or retake the
                  self-checks.
                </p>
              </div>
            ) : (
              <form
                className="mt-5"
                onSubmit={(e) => {
                  e.preventDefault();
                  submitFlagForm();
                }}
              >
                <label className="font-mono text-11 uppercase tracking-wider text-slate-500">
                  Submit the flag you captured
                </label>
                <div className="mt-2 flex gap-2">
                  <input
                    type="text"
                    autoComplete="off"
                    spellCheck={false}
                    placeholder="k8labs{...}"
                    value={flagInput}
                    onChange={(e) => {
                      setFlagInput(e.target.value);
                      if (flagStatus === "wrong") setFlagStatus("idle");
                    }}
                    className="min-w-0 flex-1 rounded-lg border border-slate-700 bg-slate-900 px-3 py-2 font-mono text-14 text-slate-100 placeholder:text-slate-600 focus:border-blue-500 focus:outline-none"
                  />
                  <button
                    type="submit"
                    disabled={!flagInput.trim() || flagStatus === "submitting"}
                    className="shrink-0 rounded-lg bg-blue-500 px-4 py-2 text-13 font-medium text-white transition-colors hover:bg-blue-400 disabled:opacity-40"
                  >
                    {flagStatus === "submitting" ? "Checking…" : "Submit"}
                  </button>
                </div>
                {flagStatus === "wrong" && (
                  <p className="mt-2 text-13 text-amber-400">
                    Not quite - that isn't the flag. Re-read the value you captured and try again.
                  </p>
                )}
              </form>
            )}

            {/* Restart is always available on the capstone - it is the "clear my
                answers / retake" control. Two-click confirm guards the wipe. */}
            {onReset && (
              <div className="mt-5 border-t border-slate-800 pt-4">
                <button
                  onClick={doReset}
                  className={`rounded-lg border px-3 py-1.5 text-13 transition-colors ${
                    confirmReset
                      ? "border-red-500/60 bg-red-500/10 text-red-300 hover:bg-red-500/20"
                      : "border-slate-800 bg-slate-900 text-slate-400 hover:border-slate-600 hover:text-slate-200"
                  }`}
                >
                  {confirmReset ? "Click again to clear all progress" : "↻ Restart lab"}
                </button>
                {confirmReset && (
                  <button
                    onClick={() => setConfirmReset(false)}
                    className="ml-2 rounded-lg px-3 py-1.5 text-13 text-slate-500 hover:text-slate-300"
                  >
                    Cancel
                  </button>
                )}
                <p className="mt-2 text-12 text-slate-600">
                  Clears your answers and solved status for {moduleName} so you can retake the
                  self-checks.
                </p>
              </div>
            )}
          </>
        )}
      </div>

      {/* stepper */}
      <div className="flex shrink-0 items-center gap-3 border-t border-slate-800 px-5 py-3">
        <div className="flex flex-1 flex-wrap gap-1.5">
          {steps.map((s, i) => {
            const current = i === idx;
            const answered = answers[s.slug];
            // Quiz dots carry their outcome: green right, red wrong, amber not yet
            // answered. Concept dots just track position. The result wins over the
            // blue "current" fill so answering recolours the dot immediately; a ring
            // still marks where you are.
            let tone: string;
            if (s.kind === "quiz" && answered !== undefined) {
              const correctIdx = s.opts?.findIndex((o) => o.correct) ?? -1;
              tone = answered === correctIdx ? "bg-emerald-500" : "bg-red-500";
            } else if (s.kind === "quiz") {
              tone = "bg-amber-500/70";
            } else if (current) {
              tone = "bg-blue-500";
            } else if (i < idx) {
              tone = "bg-slate-600";
            } else {
              tone = "bg-slate-800";
            }
            return (
              <button
                key={s.slug}
                aria-label={`Go to step ${i}`}
                onClick={() => go(i)}
                className={`h-2 w-2 rounded-full transition-transform hover:scale-125 ${tone} ${
                  current ? "scale-125 ring-2 ring-slate-300/50" : ""
                }`}
              />
            );
          })}
        </div>
        <span className="font-mono text-11 tabular-nums text-slate-600">
          {idx} / {total - 1}
        </span>
        <div className="flex gap-1.5">
          <button
            onClick={() => go(idx - 1)}
            disabled={idx === 0}
            className="rounded-lg border border-slate-800 bg-slate-900 px-3 py-1.5 text-13 text-slate-300 transition-colors hover:border-slate-600 disabled:opacity-40"
          >
            Back
          </button>
          <button
            onClick={() => go(idx + 1)}
            disabled={atEnd}
            className="rounded-lg bg-blue-500 px-3 py-1.5 text-13 font-medium text-white transition-colors hover:bg-blue-400 disabled:opacity-40"
          >
            {idx === 0 ? "Start →" : "Next →"}
          </button>
        </div>
      </div>
    </div>
  );
}
